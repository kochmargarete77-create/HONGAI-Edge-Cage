import type { CustomerConfig } from './config.js';

export interface LandingCredentials {
  username: string;
  password: string;
}

function managedRuleTargets(config: CustomerConfig): string[] {
  const targets = new Set<string>(['api.ipify.org']);
  for (const entry of config.network.allowedDomains) {
    targets.add(entry.replace(/^\*\./, '').replace(/:\d+$/, ''));
  }
  return [...targets];
}

export function credentialsFromEnvironment(config: CustomerConfig): LandingCredentials {
  const username = process.env[config.chain.landing.usernameSecretRef];
  const password = process.env[config.chain.landing.passwordSecretRef];
  if (!username || !password) {
    throw new Error(
      `Missing landing credentials. Set ${config.chain.landing.usernameSecretRef} and ` +
      `${config.chain.landing.passwordSecretRef} in the installer process environment.`
    );
  }
  return { username, password };
}

export function renderClashScript(
  config: CustomerConfig,
  credentials: LandingCredentials
): string {
  const specification = {
    sourceGroupName: config.chain.clashProfileName,
    frontGroupName: config.chain.frontGroupName,
    preferredFrontNode: config.chain.preferredFrontNode,
    landingProxyName: 'HONG AI Edge Cage | Final Exit',
    failClosedGroupName: 'HONG AI Edge Cage | Claude ONLY',
    landing: {
      type: config.chain.landing.type,
      server: config.chain.landing.host,
      port: config.chain.landing.port,
      username: credentials.username,
      password: credentials.password
    },
    routeDomains: managedRuleTargets(config)
  };

  return `// Generated by HONG AI Edge Cage. Contains customer proxy credentials.\n` +
`// Import only into the authorized customer's Clash.Meta-compatible client.\n` +
`function main(config, profileName) {\n` +
`  const spec = ${JSON.stringify(specification, null, 2)};\n` +
`  config.proxies = Array.isArray(config.proxies) ? config.proxies : [];\n` +
`  config["proxy-groups"] = Array.isArray(config["proxy-groups"]) ? config["proxy-groups"] : [];\n` +
`  config.rules = Array.isArray(config.rules) ? config.rules : [];\n` +
`\n` +
`  const source = config["proxy-groups"].find((group) => group && group.name === spec.sourceGroupName);\n` +
`  if (!source || !Array.isArray(source.proxies)) {\n` +
`    throw new Error("HONG AI Edge Cage: source proxy group not found: " + spec.sourceGroupName);\n` +
`  }\n` +
`\n` +
`  const candidates = source.proxies.filter((name) =>\n` +
`    typeof name === "string" && name !== "DIRECT" && name !== "REJECT"\n` +
`  );\n` +
`  if (candidates.length === 0) {\n` +
`    throw new Error("HONG AI Edge Cage: source group contains no usable front-hop node.");\n` +
`  }\n` +
`  const orderedCandidates = candidates.includes(spec.preferredFrontNode)\n` +
`    ? [spec.preferredFrontNode, ...candidates.filter((name) => name !== spec.preferredFrontNode)]\n` +
`    : candidates;\n` +
`\n` +
`  const managedGroups = new Set([spec.frontGroupName, spec.failClosedGroupName]);\n` +
`  config.proxies = config.proxies.filter((proxy) => proxy && proxy.name !== spec.landingProxyName);\n` +
`  config["proxy-groups"] = config["proxy-groups"].filter((group) => !group || !managedGroups.has(group.name));\n` +
`\n` +
`  config.proxies.unshift({\n` +
`    name: spec.landingProxyName,\n` +
`    type: spec.landing.type,\n` +
`    server: spec.landing.server,\n` +
`    port: spec.landing.port,\n` +
`    username: spec.landing.username,\n` +
`    password: spec.landing.password,\n` +
`    udp: true,\n` +
`    "ip-version": "ipv4",\n` +
`    "dialer-proxy": spec.frontGroupName\n` +
`  });\n` +
`  config["proxy-groups"].unshift(\n` +
`    { name: spec.failClosedGroupName, type: "select", proxies: [spec.landingProxyName] },\n` +
`    { name: spec.frontGroupName, type: "select", proxies: orderedCandidates }\n` +
`  );\n` +
`\n` +
`  const managedRules = spec.routeDomains.map((domain) =>\n` +
`    "DOMAIN-SUFFIX," + domain + "," + spec.failClosedGroupName\n` +
`  );\n` +
`  config.rules = [\n` +
`    ...managedRules,\n` +
`    ...config.rules.filter((rule) =>\n` +
`      typeof rule !== "string" || !rule.includes("," + spec.failClosedGroupName)\n` +
`    )\n` +
`  ];\n` +
`\n` +
`  return config;\n` +
`}\n`;
}
